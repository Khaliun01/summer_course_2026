function setup() {
    createCanvas(600, 400);
}
function draw() {
    background("#dff6ff");
    drawTree()
}
function drawTree() {
    fill("#5d4907ff")
    rect(300, 200, 50, 200)
    fill('#319216ff')
    circle(325, 180, 120)
    circle(280, 190, 90)
    circle(370, 190, 90)
    circle(325, 130, 90)
}